#!/usr/bin/env python3
"""Experiment 1 of `docs/specs/2026-08-16-overlap-speaker-arms-prereg.md`.

Five arms, two estimands, one primary comparison, zero confirmations.

  MECHANISTIC (the speaker-information test) - edit distance inside the mask M only,
  scored on the MASK's own partition so every arm is scored on the identical token set.
  PRIMARY: ov_turn_select - ov_turn_select_placebo, matched windows, search partition.

  OPERATIONAL (shipping impact) - whole-window out-of-fold WER through the autoresearch
  harness, which journals each arm against W with the frozen gates and the denominator.

NO CONFIRMATION IS SPENT. The hypothesis was generated by the parent experiment's
measurement on all 247 windows, confirmation cities included, so hiding four cities now
would buy nothing; see §1.1 of the preregistration. `freeze_confirmation_batch` is
never called from here.

The placebo is evaluated over N_PLACEBO draws and a bootstrap replicate resamples
meetings AND, independently per window, which draw that window contributes - so its
Monte-Carlo uncertainty is inside the interval rather than conditioned away.

Writes results_overlap_arms.json (aggregates only, no transcript text).

Env: SC (cache dir) N_BOOT (10000) N_PLACEBO (20)
"""
