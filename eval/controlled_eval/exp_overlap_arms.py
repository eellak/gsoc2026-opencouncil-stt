import collections
import json
import os
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from eval.controlled_eval import overlap_arms as OA                   # noqa: E402
from eval.controlled_eval.autoresearch import (Registry,              # noqa: E402
                                               assert_partition,
                                               search_partition,
                                               summary_line)
from eval.controlled_eval.exp_fusion_deletions import rates, sdi      # noqa: E402
from eval.controlled_eval.fusion_lab import load_substrate            # noqa: E402
from eval.controlled_eval.scoring import cluster_bootstrap, head2head  # noqa: E402

N_BOOT = int(os.environ.get("N_BOOT", "10000"))
N_PLACEBO = int(os.environ.get("N_PLACEBO", "20"))
OUT = Path(__file__).with_name("results_overlap_arms.json")

HYPOTHESES = {
    "ov_mask_select": (
        "Restricting whole-hypothesis selection to the detected-overlap neighbourhood "
        "and leaving W everywhere else is a locality-free ablation: it separates "
        "attending to overlap from cutting at the speaker handover."),
    "ov_turn_select": (
        "Inside the detected-overlap neighbourhood, cutting at the speaker handover "
        "and selecting per cell carries the round-2 overlap positive onto W."),
    "ov_turn_select_placebo": (
        "The mandatory control: the same construction with equally many cuts drawn "
        "from non-handover boundaries inside the same mask."),
    "ov_turn_compose": (
        "Inside the detected-overlap neighbourhood, re-align the trio per cell and "
        "re-vote per column with a cell-local pivot, so the arm keeps composing "
        "instead of handing the cell to one system."),
    "ov_turn_compose_placebo": (
        "The mandatory control for the composing arm, with placebo cuts inside the "
        "same mask."),
}


def log(m):
    print(m, flush=True)


def _paired_ci(rows_a, rows_b, clusters, n_boot=N_BOOT):
    """WER contrast as a ratio of sums inside every replicate. Denominators shared."""
    ca = [(r[0] + r[1] + r[2], r[3]) for r in rows_a]
    cb = [(r[0] + r[1] + r[2], r[3]) for r in rows_b]
    return cluster_bootstrap(ca, cb, clusters, n_boot=n_boot)


def _mech_ci(a_draws, b_draws, clusters, n_boot=N_BOOT, seed=7):
    """Mask-local error-rate difference, resampling meetings AND placebo draws.

    `a_draws[i]` / `b_draws[i]` are lists of (edit distance, ref tokens) over the
    N_PLACEBO draws of window i - one entry for a deterministic arm. A replicate picks
    meetings with replacement and, independently per window, one draw index, so the
    interval carries the placebo's Monte-Carlo uncertainty instead of conditioning on
    an average.
    """
    groups: dict = collections.defaultdict(list)
    for i, c in enumerate(clusters):
        groups[c].append(i)
    keys = sorted(groups)
    rng = np.random.default_rng(seed)
    A = [np.array(x, dtype=float) for x in a_draws]
    B = [np.array(x, dtype=float) for x in b_draws]

    def point(idx, pick):
        na = sum(A[i][pick[i] % len(A[i])][0] for i in idx)
        nb = sum(B[i][pick[i] % len(B[i])][0] for i in idx)
        den = sum(A[i][0][1] for i in idx)
        return (na - nb) / den if den else np.nan

    # The point estimate averages over draws (expected placebo performance); the
    # interval below resamples a draw per window so the Monte-Carlo error is inside it.
    den = sum(A[i][0][1] for i in range(len(clusters)))
    obs = ((sum(A[i][:, 0].mean() for i in range(len(clusters)))
            - sum(B[i][:, 0].mean() for i in range(len(clusters)))) / den
           if den else None)
    out = np.empty(n_boot)
    for r in range(n_boot):
        pk = rng.integers(0, len(keys), len(keys))
        idx = [i for k in pk for i in groups[keys[k]]]
        pick = {i: int(rng.integers(0, 1 << 20)) for i in idx}
        out[r] = point(idx, pick)
    lo, hi = np.nanpercentile(out, [2.5, 97.5])
    return {"delta": float(obs) if obs is not None else None,
            "ci95": [float(lo), float(hi)],
            "excludes_zero": bool(lo > 0 or hi < 0),
            "n_clusters": len(keys), "n_boot": n_boot}


def _mech_rate(draws):
    num = sum(np.array(d, dtype=float)[:, 0].mean() for d in draws)
    den = sum(d[0][1] for d in draws)
    return num / den if den else None


def build_arm(cls, windows):
    """Apply one arm to every window over N_PLACEBO draws.

    Returns (whole-window SDI rows for draw 1, mask-local (edist, n) per draw,
    per-window info).
    """
    rows, mech, info = [], [], []
    n_draws = N_PLACEBO if cls.cut_source == "placebo" else 1
    for w in windows:
        ctx = OA.context(w)
        per_draw, matched, dose, replaced = [], True, 0, 0
        first_out = None
        for d in range(1, n_draws + 1):
            arm = cls()
            arm.draw = d
            out, meta = arm.build(ctx)
            matched = matched and meta["matched"]
            dose, replaced = meta["dose"], max(replaced, meta["replaced"])
            toks = list(w.w_tokens) if out is None else out
            if first_out is None:
                first_out = toks
            per_draw.append(OA.mask_rows(ctx, toks))
        rows.append(sdi(" ".join(w.ref), " ".join(first_out)))
        mech.append(per_draw)
        info.append({"matched": matched, "dose": dose, "replaced": replaced})
    return rows, mech, info


def main() -> None:
    sub = load_substrate()
    assert_partition(sub)
    ssub = search_partition(sub)
    log(f"search partition: {json.dumps(ssub.meta)}")

    windows = list(ssub.windows)
    clusters = [w.meeting for w in windows]

    built = {}
    for name, cls in OA.ARMS.items():
        log(f"building {name} ...")
        built[name] = build_arm(cls, windows)

    rows_w = [sdi(" ".join(w.ref), " ".join(w.w_tokens)) for w in windows]
    mech_w = [[OA.mask_rows(OA.context(w), list(w.w_tokens))] for w in windows]

    matched = [i for i in range(len(windows))
               if all(built[n][2][i]["matched"] for n in OA.ARMS)]
    zero_dose = [i for i in range(len(windows))
                 if built["ov_turn_select"][2][i]["dose"] == 0]
    log(f"matched windows {len(matched)}/{len(windows)}, "
        f"zero-dose {len(zero_dose)}")

    res = {
        "spec": "docs/specs/2026-08-16-overlap-speaker-arms-prereg.md",
        "partition": "search (6 cities)", "confirmations_spent": 0,
        "confirmation_note": "the hypothesis was generated on all 247 windows, "
                             "confirmation cities included; no batch is frozen",
        "n_windows": len(windows), "n_meetings": len(set(clusters)),
        "n_placebo_draws": N_PLACEBO,
        "matched_windows": len(matched),
        "unmatched_windows": len(windows) - len(matched),
        "zero_dose_windows": len(zero_dose),
        "arms": {}, "mechanistic": {}, "operational": {}, "exposure": {},
    }

    res["arms"]["W"] = rates(rows_w)
    res["mechanistic"]["W"] = _mech_rate(mech_w)
    res["exposure"]["mask_ref_tokens"] = sum(m[0][1] for m in mech_w)
    res["exposure"]["all_ref_tokens"] = sum(r[3] for r in rows_w)
    res["exposure"]["mask_share_of_ref_tokens"] = (
        res["exposure"]["mask_ref_tokens"] / max(res["exposure"]["all_ref_tokens"], 1))

    for name in OA.ARMS:
        rows, mech, info = built[name]
        res["arms"][name] = rates(rows)
        res["mechanistic"][name] = _mech_rate(mech)
        res["exposure"][name] = {
            "replaced_tokens": sum(x["replaced"] for x in info),
            "interior_cuts": sum(x["dose"] for x in info),
            "windows_touched": sum(1 for x in info if x["replaced"] > 0),
        }

    def mech_contrast(a, b, label, idx=None):
        ii = list(range(len(windows))) if idx is None else idx
        da = [built[a][1][i] if a != "W" else mech_w[i] for i in ii]
        db = [built[b][1][i] if b != "W" else mech_w[i] for i in ii]
        cl = [clusters[i] for i in ii]
        res["mechanistic"][f"{a} vs {b}" + ("" if idx is None else " (matched)")] = \
            _mech_ci(da, db, cl)

    def op_contrast(a, b, label, idx=None):
        ii = list(range(len(windows))) if idx is None else idx
        ra = [built[a][0][i] if a != "W" else rows_w[i] for i in ii]
        rb = [built[b][0][i] if b != "W" else rows_w[i] for i in ii]
        cl = [clusters[i] for i in ii]
        out = _paired_ci(ra, rb, cl)
        out["head2head"] = head2head([(r[0] + r[1] + r[2], r[3]) for r in ra],
                                     [(r[0] + r[1] + r[2], r[3]) for r in rb])
        out["del_rate_delta"] = rates(ra)["del_rate"] - rates(rb)["del_rate"]
        res["operational"][label] = out

    # ---- PRIMARY --------------------------------------------------------------
    mech_contrast("ov_turn_select", "ov_turn_select_placebo", "primary", matched)
    # ---- secondary ------------------------------------------------------------
    mech_contrast("ov_turn_compose", "ov_turn_compose_placebo", "sec", matched)
    for a in OA.ARMS:
        mech_contrast(a, "W", "vsW")
        op_contrast(a, "W", f"{a} vs W")
    op_contrast("ov_turn_select", "ov_turn_select_placebo",
                "ov_turn_select vs placebo (matched)", matched)
    op_contrast("ov_turn_compose", "ov_turn_compose_placebo",
                "ov_turn_compose vs placebo (matched)", matched)

    # single-item domination on the primary
    prim = res["mechanistic"]["ov_turn_select vs ov_turn_select_placebo (matched)"]
    per_meeting: dict = collections.defaultdict(float)
    for i in matched:
        a = np.array(built["ov_turn_select"][1][i], dtype=float)[:, 0].mean()
        b = np.array(built["ov_turn_select_placebo"][1][i], dtype=float)[:, 0].mean()
        per_meeting[clusters[i]] += a - b
    tot = sum(abs(v) for v in per_meeting.values())
    worst = max(per_meeting.items(), key=lambda kv: abs(kv[1])) if per_meeting else None
    prim["domination"] = (abs(worst[1]) / tot) if (worst and tot) else 0.0
    prim["domination_meeting"] = worst[0] if worst else None
    prim["meetings_touched"] = sum(1 for v in per_meeting.values() if v != 0)

    # ---- the harness: journal each arm against W, with the denominator -----------
    reg = Registry()
    handles, journal = {}, {}
    for name, cls in OA.ARMS.items():
        h = reg.register(name, HYPOTHESES[name], cls, resume=True)
        handles[name] = h
        if h.idea_key in reg.searched():
            log(f"{name}: already searched, keeping the journalled result")
            continue
        s = reg.run_search(h, ssub, n_boot=2000)
        journal[name] = s
        log("  " + summary_line(s))
    res["harness"] = {"leaderboard": reg.leaderboard(),
                      "this_run": {k: {kk: v[kk] for kk in
                                       ("dwer", "wild_p", "wild_p_min_effect",
                                        "percentile_ci95", "del_rate", "ins_rate",
                                        "meetings_touched", "domination",
                                        "windows_changed_vs_W", "screen")}
                                   for k, v in journal.items()}}

    anchors = {k: 0 for k in ("W", "REF")}
    tokens = dict(anchors)
    for w in windows:
        c = OA.context(w)
        for k in anchors:
            anchors[k] += c.anchors[k]
        tokens["W"] += len(c.w_tokens)
        tokens["REF"] += len(c.ref)
    res["anchor_coverage"] = {k: anchors[k] / max(tokens[k], 1) for k in anchors}

    OUT.write_text(json.dumps(res, indent=1, ensure_ascii=False), encoding="utf-8")
    log(f"-> {OUT}")
    for k, v in res["arms"].items():
        log(f"  {k:26s} wer={v['wer']:.5f} del={v['del_rate']:.5f} "
            f"ins={v['ins_rate']:.5f} mask_err={res['mechanistic'][k]:.5f}")
    log(json.dumps({k: v for k, v in res["mechanistic"].items()
                    if isinstance(v, dict)}, indent=1))


if __name__ == "__main__":
    main()
